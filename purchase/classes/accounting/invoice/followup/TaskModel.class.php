namespace purchase\accounting\invoice\followup;

class TaskModel extends \core\followup\TaskModel {

    public static function getDescription(): string {
        return "A task is generated from a task model when a purchase invoice is created or change status.";
    }

    public static function getColumns(): array {
        return [

            'entity' => [
                'type'              => 'string',
                'description'       => "Namespace of the concerned entity.",
                'default'           => 'purchase\accounting\invoice\PurchaseInvoice'
            ],

            'trigger_event_id' => [
                'type'              => 'many2one',
                'foreign_object'    => 'purchase\accounting\invoice\followup\TaskEvent',
                'description'       => "The trigger event associated with the task model.",
                'required'          => false
            ],

            'deadline_event_id' => [
                'type'              => 'many2one',
                'foreign_object'    => 'purchase\accounting\invoice\followup\TaskEvent',
                'description'       => "The deadline event associated with the task model.",
                'domain'            => ['event_type', '=', 'date_field']
            ],

            'tasks_ids' => [
                'type'              => 'one2many',
                'foreign_object'    => 'purchase\accounting\invoice\followup\Task',
                'foreign_field'     => 'task_model_id',
                'description'       => "The purchase invoice tasks generated by the task model."
            ]

        ];
    }

    public static function getConstraints(): array {
        return [

            'entity' => [
                'not_allowed' => [
                    'message'   => 'Entity must be "purchase\accounting\invoice\PurchaseInvoice".',
                    'function'  => function ($entity, $values) {
                        return $entity === 'purchase\accounting\invoice\PurchaseInvoice';
                    }
                ]
            ]

        ];
    }
}
